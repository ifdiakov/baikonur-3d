import {readFile,writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {MUSEUM_KNOWLEDGE_VERSION} from '../src/museum-knowledge.js';

// The menu and concise site cards need only this reviewed catalogue. Longer
// articles, references and the renderer are fetched after the map is usable.
const sourceUrl=new URL('../data/buran-knowledge.json',import.meta.url);
const outputUrl=new URL('../src/museum-knowledge-index.js',import.meta.url);
const source=await readFile(sourceUrl,'utf8'),data=JSON.parse(source);
const fields=['id','title','subtitle','summary','siteId','evidenceType'];
const project=records=>Object.fromEntries(Object.entries(records||{}).map(([id,record])=>{
 if(record.id!==id||typeof record.title!=='string')throw new Error('Invalid knowledge catalogue entry: '+id);
 return [id,Object.fromEntries(fields.filter(key=>Object.hasOwn(record,key)).map(key=>[key,record[key]]))];
}));
const index={version:MUSEUM_KNOWLEDGE_VERSION,edition:data.edition||null,
 sourceRevision:createHash('sha256').update(source).digest('hex').slice(0,16),
 sites:project(data.sites),rockets:project(data.rockets),stories:project(data.stories),
 evidenceTypes:Object.fromEntries(Object.entries(data.evidenceTypes||{}).map(([id,entry])=>[id,{label:entry.label}])),
 sourceCount:Object.keys(data.sources||{}).length,sourceConflictCount:data.sourceConflicts?.length||0};
const generated='// Generated by scripts/build-knowledge-index.mjs from data/buran-knowledge.json.\n'+
 '// Descriptions and menu labels only; complete articles retain their original source citations.\n'+
 'export const MUSEUM_KNOWLEDGE_INDEX=Object.freeze('+JSON.stringify(index)+');\n';
if(process.argv.includes('--check')){
 if(await readFile(outputUrl,'utf8')!==generated)throw new Error('Knowledge index is stale. Run node scripts/build-knowledge-index.mjs.');
}else await writeFile(outputUrl,generated);
console.log(JSON.stringify({indexBytes:Buffer.byteLength(generated),corpusBytes:Buffer.byteLength(source),
 entries:Object.keys(index.sites).length+Object.keys(index.rockets).length+Object.keys(index.stories).length,
 sourceRevision:index.sourceRevision,checked:process.argv.includes('--check')}));
