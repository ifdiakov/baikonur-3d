import assert from 'node:assert/strict';
import fs from 'node:fs';
import * as THREE from 'three';
import {createMuseumGeography} from '../src/osm-geography.js';
import {createEastLightingZone} from '../src/east-lighting-zone.js';
import {createLightField} from '../src/light-field.js';
import {ARCHIVE_MAP} from '../src/archive-manifest.js';
const catalog=JSON.parse(fs.readFileSync('data/catalog.json')),matches=JSON.parse(fs.readFileSync('data/osm/catalog-matches.json'));
const facilities=JSON.parse(fs.readFileSync('data/osm/facilities.geojson'));
const geo=createMuseumGeography({catalog,matches});
const project=(lon,lat)=>{const[x,z]=geo.project(lon,lat);return[(x-650)*3.4,(z-522.5)*3.4];};
const zone=createEastLightingZone({facilities,project});
const site=id=>geo.sites.find(s=>s.id===id),world=s=>[(s.x-650)*3.4,(s.y-522.5)*3.4];
assert.ok(!zone.isPowered(...world(site('pad-41'))));
for(const id of ['pad-42','pad-45','pad-31','pad-1','pad-251','city'])assert.ok(zone.isPowered(...world(site(id))),id+' remains powered');
assert.equal(site('pad-41').geoSource.refs[0].id,169401013);
assert.equal(site('pad-41').firstYear,1960);
assert.equal(ARCHIVE_MAP.filter(s=>s.id==='pad-41').length,1);
assert.equal(site('pad-251').organisation.org,'РГП «Инфракос»');
const without=JSON.parse(JSON.stringify(catalog));without.sites=without.sites.filter(s=>s.id!=='pad-41');
const prior=createMuseumGeography({catalog:without,matches});
for(const s of prior.sites){const now=site(s.id);assert.deepEqual([now.x,now.y],[s.x,s.y],'Adding 41 must not shift '+s.id);}
const root=new THREE.Group(),records=[{x:0,y:0,z:0,height:3,powered:false},{x:10,y:0,z:0,height:3,powered:true}];
const field=createLightField(root,records,{poles:true,pools:true});
const glow=field.root.children.find(m=>m.isPoints),instances=field.root.children.filter(m=>m.isInstancedMesh),m=new THREE.Matrix4();
assert.deepEqual([...glow.geometry.attributes.enabled.array],[0,1]);
instances[0].getMatrixAt(0,m);assert.ok(m.elements[13]>0,'An unpowered pole remains visible');
instances[2].getMatrixAt(0,m);assert.ok(m.elements[13]<-50000,'An unpowered lamp has no ground glow');
records[0].powered=true;field.sync();assert.deepEqual([...glow.geometry.attributes.enabled.array],[1,1]);
console.log('SITE41_LIGHTING_PASS',JSON.stringify({coordinate:site('pad-41').geoSource.sourceLonLat,cutoff:zone.stats(),site42Lit:true,existingSitesUnchanged:true}));
