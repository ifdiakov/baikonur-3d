import assert from 'node:assert/strict';
import {chromium} from 'playwright';
const url=process.env.BAIKONUR_URL||'http://127.0.0.1:8765/';
const browser=await chromium.launch({headless:true,args:['--no-sandbox','--use-gl=angle','--use-angle=swiftshader','--enable-webgl','--enable-unsafe-swiftshader']});
const page=await browser.newPage({viewport:{width:1440,height:900},deviceScaleFactor:1});
const errors=[];
page.on('pageerror',error=>errors.push(error.message));
try{
 await page.goto(url,{waitUntil:'domcontentloaded',timeout:90000});
 await page.waitForFunction(()=>document.body.classList.contains('museum-ready')&&window.__BAIKONUR_QA?.stats?.(),null,{timeout:180000});
 assert.equal(await page.locator('#complexHistoryAccordion').count(),1);
 await page.evaluate(()=>{document.querySelector('#complexHistoryAccordion').open=true;});
 const entries=page.locator('#complexHistoryAccordion [data-museum-action^="history:"]');
 assert.equal(await entries.count(),10,'All sourced history chapters appear in the sidebar');
 await page.evaluate(()=>document.querySelector('[data-museum-action="history:why"]').click());
 const panel=page.locator('#complexHistoryPanel');
 await panel.waitFor({state:'visible'});
 assert.match(await panel.locator('h3').textContent(),/Тюра-Там/);
 assert(await panel.locator('.complex-history__sources a').count()>=1);
 const links=await panel.locator('.complex-history__sources a').evaluateAll(es=>es.map(e=>({href:e.href,target:e.target})));
 assert(links.every(x=>x.href.startsWith('https://')&&x.target==='_blank'));
 await page.evaluate(()=>document.querySelector('.complex-history__footer button:last-child').click());
 assert.match(await panel.locator('h3').textContent(),/Секретное решение/);
 await page.evaluate(()=>document.querySelector('.complex-history__button--ghost').click());
 assert.equal(await page.locator('#yearVal').textContent(),'1955');
 await page.evaluate(()=>document.querySelector('.complex-history__close').click());
 assert.equal(await panel.isVisible(),false);
 assert.equal(errors.length,0,JSON.stringify(errors));
 console.log('COMPLEX_HISTORY_BROWSER_PASS',JSON.stringify({chapters:await entries.count(),links:links.length,changedYear:1955,errors:errors.length}));
}catch(e){console.error('COMPLEX_HISTORY_BROWSER_ERROR',e.message);throw e;}finally{await browser.close();}
