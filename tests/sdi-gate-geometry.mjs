import assert from 'node:assert/strict';
import * as THREE from 'three';
import {NodeIO} from '@gltf-transform/core';
import {ALL_EXTENSIONS} from '@gltf-transform/extensions';
import {getBounds} from '@gltf-transform/functions';
import {MeshoptDecoder} from '../src/vendor/meshopt_decoder-v1.mjs';
import {buildMzkSdi} from '../src/mzk-sdi.js';
import {sdiController} from '../src/mzk-sdi-stand.js?v=20261102-sdi-energia-m-v1';
const root=new THREE.Group();const built=buildMzkSdi(root),gate=sdiController(root),meta=root.userData.mzkSdi.sdi;
let leaf;root.traverse(o=>{if(o.userData.museumComponent==='sdi-sliding-leaf')leaf=o;});
assert(leaf);assert.equal(meta.rocketMount.modelId,'energia-m');
const frame=leaf.parent,local=p=>frame.localToWorld(new THREE.Vector3(...p));
const blocker=()=>{
 root.updateMatrixWorld(true);
 const from=local([-5.5,28,40]),to=local([-5.5,28,12]);
 return new THREE.Raycaster(from,to.clone().sub(from).normalize(),0,from.distanceTo(to)).intersectObject(root,true);
};
gate.update(0);assert.equal(gate.stats().state,'closed');assert(blocker().length,'Closed leaf must occlude the rocket');
const fixed=root.children.filter(o=>o!==frame).map(o=>o.matrix.toArray());
gate.setOpen(true,0);gate.update(4000);assert.equal(gate.stats().progress,.5);
const halfway=leaf.position.clone();gate.setOpen(false,4000);assert(halfway.equals(leaf.position),'Reversal must not jump');
gate.update(6000);assert(gate.stats().progress<.5);gate.setOpen(true,6000);gate.update(14000);
assert.equal(gate.stats().state,'open');assert.equal(blocker().length,0,'Open leaf must expose the rocket with no baked-in duplicate');
assert.deepEqual(root.children.filter(o=>o!==frame).map(o=>o.matrix.toArray()),fixed);
// Decode the actual model, not just the manifest, and check its placement.
await MeshoptDecoder.ready;
const doc=await new NodeIO().registerExtensions(ALL_EXTENSIONS).registerDependencies({'meshopt.decoder':MeshoptDecoder}).read('assets/models/rockets/energia-m.glb');
const b=getBounds(doc.getRoot().listScenes()[0]);
const inverse=frame.matrixWorld.clone().invert();
const mount=new THREE.Vector3(...meta.rocketMount.position).applyMatrix4(inverse);
const rb=new THREE.Box3(new THREE.Vector3(...b.min).add(mount),new THREE.Vector3(...b.max).add(mount));
assert(rb.min.x>-20&&rb.max.x<10&&rb.min.z>-16&&rb.max.z<20);
assert(rb.min.y>=2.799&&rb.max.y<101.4);
const leafBounds=new THREE.Box3().setFromObject(leaf).applyMatrix4(inverse);
assert(leafBounds.min.x>rb.max.x+3,'Open gate must clear both side boosters');
assert(leafBounds.max.x<57,'Door stays inside the projecting upper guide');
assert(leafBounds.min.z>25.1,'Door depth ties clear the concrete jamb throughout travel');
gate.setOpen(false,14000);gate.update(22000);assert.equal(gate.stats().progress,0);assert(blocker().length);
assert.doesNotThrow(()=>JSON.stringify(built));
console.log('SDI_GATE_GEOMETRY_PASS',JSON.stringify({gate:gate.stats(),rocketHeight:b.max[1]-b.min[1],openClearance:leafBounds.min.x-rb.max.x,draws:built.meshCount}));
